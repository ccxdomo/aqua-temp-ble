const ALL_HOOKS = Object.assign({}, HOOKS_METHODCHANNEL, HOOKS_COMMANDS);

// ---------------------------------------------------------------------------
// 2. Output: one compact line per event, plus a raw hexdump of any byte-ish
//    payload found in the arguments. Everything is also kept in memory so it
//    can be dumped on demand (send({"cmd":"dump"}) from the Frida REPL).
// ---------------------------------------------------------------------------

const EVENTS = [];
let EVENT_COUNT = 0;

function nowIso() {
    return new Date().toISOString().substr(11, 12); // HH:MM:SS.mmm
}

function hexdump(bytes) {
    const out = [];
    for (let i = 0; i < bytes.length; i += 16) {
        const chunk = bytes.slice(i, i + 16);
        const hex = Array.from(chunk).map(b => b.toString(16).padStart(2, '0')).join(' ');
        const asc = Array.from(chunk).map(b => (b >= 32 && b < 127) ? String.fromCharCode(b) : '.').join('');
        out.push(`    ${i.toString(16).padStart(4, '0')}  ${hex.padEnd(47)}  |${asc}|`);
    }
    return out.join('\n');
}

// Try to turn a decoded Dart value into a byte array (Uint8List / List<int>).
function toBytes(value) {
    if (value == null) return null;
    if (Array.isArray(value)) {
        if (value.length && value.every(v => typeof v === 'number' && v >= 0 && v <= 255)) {
            return value;
        }
        // {"0":..,"1":..} map form used by blutter for typed arrays
        if (typeof value === 'object') {
            const keys = Object.keys(value).filter(k => /^\d+$/.test(k));
            if (keys.length) {
                return keys.sort((a, b) => a - b).map(k => value[k] & 0xff);
            }
        }
    }
    if (typeof value === 'object' && value !== null) {
        const keys = Object.keys(value).filter(k => /^\d+$/.test(k));
        if (keys.length) {
            return keys.sort((a, b) => a - b).map(k => value[k] & 0xff);
        }
    }
    return null;
}

function report(name, addr, args) {
    EVENT_COUNT++;
    const entry = {
        n: EVENT_COUNT,
        t: nowIso(),
        hook: name,
        addr: '0x' + addr.toString(16),
        args: args,
    };
    EVENTS.push(entry);

    console.log(`\n[${entry.t}] #${entry.n} ${name} @ ${entry.addr}`);
    for (const a of args) {
        console.log(`   arg[${a.i}] ${a.cls} = ${a.preview}`);
        const b = toBytes(a.value);
        if (b && b.length) {
            console.log('   ---- raw bytes ----');
            console.log(hexdump(b));
        }
    }
}

// ---------------------------------------------------------------------------
// 3. Hook installation
// ---------------------------------------------------------------------------

function installHooks() {
    if (!libapp) {
        console.error('!! libapp not resolved yet');
        return;
    }
    console.log(`libapp base = ${libapp}`);
    console.log(`Installing ${Object.keys(ALL_HOOKS).length} hooks...`);

    for (const [name, addr] of Object.entries(ALL_HOOKS)) {
        try {
            Interceptor.attach(libapp.add(addr), {
                onEnter: function () {
                    try {
                        init(this.context);
                        const args = [];
                        // Decode up to 4 arguments; getArg() is provided by blutter.
                        for (let i = 0; i < 4; i++) {
                            let ptr;
                            try { ptr = getArg(this.context, i); } catch (e) { break; }
                            if (ptr.isNull() || ptr.equals(ptr_0)) break;

                            let cls = null, values = null, tptr = ptr;
                            try {
                                [tptr, cls, values] = getTaggedObjectValue(ptr);
                            } catch (e) {
                                args.push({ i, cls: '?', preview: String(ptr), value: null });
                                continue;
                            }
                            const clsName = (cls && cls.name) ? cls.name : '?';
                            let preview;
                            try {
                                preview = JSON.stringify(values, (k, v) => {
                                    if (typeof v === 'string' && v.length > 200) return v.substr(0, 200) + '...';
                                    return v;
                                });
                            } catch (e) {
                                preview = String(values);
                            }
                            if (preview && preview.length > 600) preview = preview.substr(0, 600) + '...';
                            args.push({ i, cls: clsName, preview, value: values });
                        }
                        report(name, addr, args);
                    } catch (e) {
                        console.log(`!! hook ${name} error: ${e}`);
                    }
                }
            });
        } catch (e) {
            console.log(`!! could not hook ${name} @ 0x${addr.toString(16)}: ${e}`);
        }
    }
    console.log('All hooks installed. Operate the app now.');
    console.log('Frida commands:   dump()   -> print all captured events as JSON');
}

// ---------------------------------------------------------------------------
// 4. Bootstrapping + export helpers
// ---------------------------------------------------------------------------

// blutter_frida.js defines tryLoadLibapp() and starts it at load time.
// By the time this file runs, libapp may or may not be resolved; poll for it.
function waitLibappAndInstall(retries) {
    if (typeof libapp !== 'undefined' && libapp !== nul_placeholder && libapp !== null) {
        installHooks();
        return;
    }
    if (retries <= 0) {
        console.error('!! libapp never resolved');
        return;
    }
    setTimeout(() => waitLibappAndInstall(retries - 1), 500);
}

// `null` is a valid value in the loaded scope; compare defensively.
const nul_placeholder = undefined;

global.dump = function () {
    console.log(JSON.stringify(EVENTS, null, 2));
    return EVENTS.length;
};

global.dumpHex = function () {
    // prints only the events whose args contained bytes
    for (const e of EVENTS) {
        for (const a of e.args) {
            const b = toBytes(a.value);
            if (b && b.length) {
                console.log(`#${e.n} ${e.t} ${e.hook}`);
                console.log(hexdump(b));
            }
        }
    }
};

global.clearEvents = function () {
    EVENTS.length = 0;
    EVENT_COUNT = 0;
    console.log('events cleared');
};

waitLibappAndInstall(120); // 60 s of retries

console.log('aqua_hooks.js loaded — waiting for libapp.so ...');
