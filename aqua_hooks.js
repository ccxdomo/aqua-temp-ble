    'vMa::write_validate_1'    : 0x5dbcd0,   // bool   (MethodCall)
    'vMa::write_map_1'         : 0x5dbc80,   // OMa    (dynamic)
    'vMa::write_validate_2'    : 0x5da5a8,   // bool   (OMa)
    'vMa::write_validate_3'    : 0x5da54c,   // bool   (OMa)
