// ============================================================================
// aqua_hooks.js — Frida instrumentation for Aqua Temp (com.phinx.poolheater4)
// ============================================================================
//
// Goal
// ----
// Read, at runtime, the Dart objects passed to the BLE command builders and to
// the MethodChannel handler, so the FRAME CONTENTS become visible even though
// the static analysis cannot decompile the function bodies (dedup_instructions
// + obfuscation).
//
// How it works
// ------------
// This file is a *thin driver* on top of `blutter_frida.js` (generated by
// blutter). That base file already provides, for THIS exact libapp.so:
//   - the `Classes` table (class id -> name/fields) incl. vMa, _UR, _nR, _lR, _cR
//   - the runtime config: compressed pointers, HeapAddressReg = 'x28'
//   - decoders: getTaggedObjectValue(), getObjectValue(), getDartString(),
//     getDartMint(), getDartDouble(), getDartArray(), getArg(), init()
//
// So: load blutter_frida.js FIRST, then this file. See README_HOOKS.md.
//
// Usage (device must be rooted or the app must be debuggable):
//   frida -U -f com.phinx.poolheater4 -l blutter_frida.js -l aqua_hooks.js
//
// Or via the blutter helper that concatenates both:
//   (concatenate blutter_frida.js + aqua_hooks.js into one file and -l it)
//
// ============================================================================

'use strict';

// ---------------------------------------------------------------------------
// 1. Hook targets — absolute addresses inside libapp.so, recovered from
//    blutter's pp.txt (Object Pool) cross-referenced with asm/ class listings.
//
//    All addresses are the low 32 bits; the real target is libapp.add(addr).
// ---------------------------------------------------------------------------

// Handler of the BLE MethodChannel ("flutter_blue_plus/methods").
// It validates a MethodCall and returns success/failure of the write.
